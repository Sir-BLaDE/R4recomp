"""Copy src/mods/*.c|h|cpp into a build directory, translating USA addresses to PAL.

The 0x8XXXXXXX literals outside comments and strings are translated by r4map; an
untranslatable address becomes 0xFFFFFFF0u (an impossible address: the matching hook stays
inert) and is listed. Comments are left as they are. The manual address file (one `USA PAL`
pair per line, pal/manual_addresses.txt) wins over the automatic translation (functions PAL
rewrote, placed by hand).

Usage: python translate_mods.py SRC_MODS DEST GENERATED_USA SCES_017.06 [MANUAL_ADDRESSES]
Writes DEST/<file> for each source and DEST/translation.txt (the list of failures).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from r4map import AddressMap, read_manual_addresses  # noqa: E402

LIT = re.compile(r"\b0x(8[0-9A-Fa-f]{7})([uUlL]*)\b")
COMMENT = re.compile(r"//[^\n]*|/\*.*?\*/|\"(?:\\.|[^\"\\])*\"", re.S)


def main():
    if len(sys.argv) < 5:
        raise SystemExit(__doc__)
    src, dest, gen, exe = sys.argv[1:5]
    manual = {}
    if len(sys.argv) > 5 and os.path.exists(sys.argv[5]):
        manual = read_manual_addresses(sys.argv[5])
    amap = AddressMap(gen, exe, sys.argv[5] if len(sys.argv) > 5 else None)
    os.makedirs(dest, exist_ok=True)
    failures, total = [], 0
    for name in sorted(os.listdir(src)):
        if not name.endswith((".c", ".h", ".cpp")):
            continue
        text = open(os.path.join(src, name), encoding="utf-8").read()
        pieces, pos = [], 0
        for m in COMMENT.finditer(text):
            pieces.append(("code", text[pos:m.start()]))
            pieces.append(("comment", m.group()))
            pos = m.end()
        pieces.append(("code", text[pos:]))

        def repl(m):
            nonlocal total
            a = int(m.group(1), 16)
            if a in manual:
                r, reason = manual[a], "manual"
            else:
                r, reason = amap.translate(a)
                if r is not None and "word-differs" in reason:
                    r = None
            total += 1
            if r is None:
                failures.append(f"{name}: 0x{a:08X} ({reason})")
                return "0xFFFFFFF0u"
            return f"0x{r:08X}{m.group(2)}"

        out = "".join(LIT.sub(repl, t) if k == "code" else t for k, t in pieces)
        out = "/* GENERATED by pal/tools/translate_mods.py (PAL SCES-01706 addresses). */\n" + out
        open(os.path.join(dest, name), "w", encoding="utf-8", newline="\n").write(out)
    with open(os.path.join(dest, "translation.txt"), "w", encoding="utf-8", newline="\n") as o:
        o.write(f"{total} literals, {len(failures)} not translated\n" + "\n".join(failures) + "\n")
    print(f"{total} literals translated or targeted, {len(failures)} not translated")
    for e in failures:
        print("  ", e)


if __name__ == "__main__":
    main()
