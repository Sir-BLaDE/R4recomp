#!/usr/bin/env python3
"""Convert a DuckStation/PCSX .cht GameShark file into C code tables.

Usage: python3 tools/cht_to_c.py mods/source/R4_60FPS_Widescreen_Patch_V2.cht src/r4_gameshark_codes.h

Only the code types the R4 patch uses are accepted (80 = 16-bit write,
D0 = 16-bit equal, execute next line). Anything else fails loudly, so a
future revision of the patch cannot be half-converted silently.
"""
import re
import sys

SUPPORTED = {0x80, 0xD0}

def ident(name: str) -> str:
    s = re.sub(r"[^0-9A-Za-z]+", "_", name).strip("_").lower()
    return "r4gs_" + (s if not s[0].isdigit() else "s_" + s)

def main() -> int:
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src, encoding="utf-8").read()
    parts = re.split(r"^\[(.*)\]\s*$", text, flags=re.M)
    out = [
        "/* Generated by tools/cht_to_c.py from " + src.split("/")[-1] + ". Do not edit. */",
        "#pragma once",
        "#include <stdint.h>",
        "typedef struct { uint8_t type; uint32_t addr; uint16_t value; } R4GsCode;",
        "",
    ]
    sections = []
    for name, body in zip(parts[1::2], parts[2::2]):
        codes = []
        for line in body.splitlines():
            line = line.strip()
            if not line or "=" in line:
                continue
            m = re.fullmatch(r"([0-9A-Fa-f]{8}) ([0-9A-Fa-f]{4})", line)
            if not m:
                raise SystemExit(f"{name}: unparsed line {line!r}")
            word = int(m.group(1), 16)
            ctype = word >> 24
            if ctype not in SUPPORTED:
                raise SystemExit(f"{name}: unsupported code type {ctype:02X} in {line}")
            addr = 0x80000000 | (word & 0x00FFFFFF)
            if addr & 1:
                raise SystemExit(f"{name}: unaligned 16-bit code {line}")
            codes.append((ctype, addr, int(m.group(2), 16)))
        if codes and codes[-1][0] == 0xD0:
            raise SystemExit(f"{name}: trailing conditional")
        cid = ident(name)
        sections.append((name, cid, len(codes)))
        out.append(f"/* [{name}] */")
        out.append(f"static const R4GsCode {cid}[{len(codes)}] = {{")
        for t, a, v in codes:
            out.append(f"    {{0x{t:02X}, 0x{a:08X}u, 0x{v:04X}u}},")
        out.append("};")
        out.append("")
    open(dst, "w", encoding="utf-8").write("\n".join(out) + "\n")
    for name, cid, n in sections:
        print(f"{cid}: {n} codes  [{name}]")
    return 0

if __name__ == "__main__":
    sys.exit(main())
